'use client';

import { useEffect, useState } from 'react';
import { RefreshCw, Newspaper } from 'lucide-react';
import { tapi, useTraining, fmtDate } from '@/lib/training/client';
import { Panel, Spinner, ErrorNote, Empty, Btn, Pill, inputCls } from '@/components/training/ui';
import { Markdown } from '@/components/training/markdown';
import { TrainerPage, useConfirm, useToast, Help } from '@/components/training/hr/kit';
import { cn } from '@/lib/utils';

export default function DigestPage() {
  const toast = useToast();
  const confirm = useConfirm();
  const { data, error, mutate } = useTraining<any[]>('/digest');
  const [week, setWeek] = useState<string>('');
  const [busy, setBusy] = useState(false);
  useEffect(() => { if (data?.length && !data.some((d) => weekKey(d) === week)) setWeek(weekKey(data[0])); }, [data, week]);
  const current = data?.find((d) => weekKey(d) === week);
  const idx = data ? data.findIndex((d) => weekKey(d) === week) : -1;

  async function generate() {
    const ok = current && weekKey(current) === weekKey(data![0])
      ? await confirm.ask({ title: 'Regenerate this week’s digest?', body: <p>The digest for the week of {fmtDate(current.week_start)} is rebuilt from the latest numbers and replaces the current text.</p>, confirmLabel: 'Regenerate', tone: 'primary' })
      : '';
    if (ok === null) return;
    setBusy(true);
    try {
      const r = await tapi<any>('/digest', { body: {} });
      const fresh = await mutate();
      if (r?.week_start) setWeek(String(r.week_start).slice(0, 10));
      else if (fresh?.[0]) setWeek(weekKey(fresh[0]));
      toast.show(r?.ai_used ? 'Digest generated by AI' : 'Digest generated (standard mode — template text)');
    } catch (e) { toast.error(e); } finally { setBusy(false); }
  }

  return (
    <TrainerPage title="Weekly coach digest"
      subtitle="A Monday summary for the sales lead: per-rep scores, what to coach, items worth listening to, AI-vs-human disagreement and AI spend."
      actions={<Btn size="sm" onClick={generate} disabled={busy}><RefreshCw className={cn('h-4 w-4', busy && 'animate-spin')} /> {busy ? 'Generating…' : 'Generate now'}</Btn>}>
      {toast.node}{confirm.node}
      <ErrorNote error={error} />
      {!data ? <Spinner /> : data.length === 0 ? (
        <Panel><Empty icon={<Newspaper className="h-5 w-5" />} title="No digests yet" body="A digest is written automatically every Monday. Generate one now to see this week’s." action={<Btn onClick={generate} disabled={busy}>Generate now</Btn>} /></Panel>
      ) : (
        <div className="space-y-4">
          <div className="flex flex-wrap items-center gap-2">
            <Btn size="sm" variant="secondary" disabled={idx >= data.length - 1} onClick={() => setWeek(weekKey(data[idx + 1]))}>← Older</Btn>
            <label className="sr-only" htmlFor="week">Week</label>
            <select id="week" className={cn(inputCls, 'w-auto')} value={week} onChange={(e) => setWeek(e.target.value)}>
              {data.map((d) => <option key={d.id} value={weekKey(d)}>Week of {fmtDate(d.week_start)}</option>)}
            </select>
            <Btn size="sm" variant="secondary" disabled={idx <= 0} onClick={() => setWeek(weekKey(data[idx - 1]))}>Newer →</Btn>
            {current && <span className="ml-auto flex items-center gap-2 text-xs text-gray-500">{current.ai_used ? <Pill tone="blue">Written by AI</Pill> : <Pill>Standard mode (template)</Pill>} created {fmtDate(current.created_at, true)}</span>}
          </div>
          {current && <Panel><div className="max-w-3xl"><Markdown source={current.body_md || ''} /></div></Panel>}
          <Help>Generated automatically each Monday morning (Pakistan time). “Generate now” rebuilds the current week’s digest. Without an AI key the digest uses a fixed template with the same numbers.</Help>
        </div>
      )}
    </TrainerPage>
  );
}

function weekKey(d: any) {
  return String(d.week_start).slice(0, 10);
}
